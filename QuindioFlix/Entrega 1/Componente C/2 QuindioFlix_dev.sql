-- 1. ESTRUCTURA ORGANIZACIONAL
------------------------------------------------------------

CREATE TABLE departamento (
    id_departamento        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre                 VARCHAR2(50 CHAR) NOT NULL,
    descripcion            VARCHAR2(250 CHAR),
    id_jefe                NUMBER,
    fecha_creacion         DATE DEFAULT SYSDATE NOT NULL,
    activo                 CHAR(1 CHAR) DEFAULT 'S' NOT NULL,

    CONSTRAINT pk_departamento PRIMARY KEY (id_departamento),
    CONSTRAINT uq_departamento_nombre UNIQUE (nombre),
    CONSTRAINT ck_departamento_activo CHECK (activo IN ('S','N'))
);

CREATE TABLE empleado (
    id_empleado            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_departamento        NUMBER NOT NULL,
    id_supervisor          NUMBER,
    nombre                 VARCHAR2(80 CHAR) NOT NULL,
    apellido               VARCHAR2(80 CHAR) NOT NULL,
    email                  VARCHAR2(150 CHAR) NOT NULL,
    telefono               VARCHAR2(20 CHAR),
    cargo                  VARCHAR2(80 CHAR) NOT NULL,
    fecha_contratacion     DATE DEFAULT SYSDATE NOT NULL,
    salario                NUMBER(12,2),
    activo                 CHAR(1 CHAR) DEFAULT 'S' NOT NULL,

    CONSTRAINT pk_empleado PRIMARY KEY (id_empleado),
    CONSTRAINT uq_empleado_email UNIQUE (email),
    CONSTRAINT ck_empleado_salario CHECK (salario IS NULL OR salario >= 0),
    CONSTRAINT ck_empleado_activo CHECK (activo IN ('S','N')),
    CONSTRAINT ck_empleado_supervisor_self CHECK (
        id_supervisor IS NULL OR id_supervisor <> id_empleado
    ),
    CONSTRAINT fk_empleado_departamento
        FOREIGN KEY (id_departamento)
        REFERENCES departamento(id_departamento),
    CONSTRAINT fk_empleado_supervisor
        FOREIGN KEY (id_supervisor)
        REFERENCES empleado(id_empleado)
);

ALTER TABLE departamento
    ADD CONSTRAINT fk_departamento_jefe
    FOREIGN KEY (id_jefe)
    REFERENCES empleado(id_empleado);

------------------------------------------------------------
-- 2. PLANES, USUARIOS Y ROLES
------------------------------------------------------------

CREATE TABLE plan_suscripcion (
    id_plan                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre                 VARCHAR2(30 CHAR) NOT NULL,
    precio_mensual         NUMBER(10,2) NOT NULL,
    pantallas_simultaneas  NUMBER(2) NOT NULL,
    calidad_video          VARCHAR2(10 CHAR) NOT NULL,
    max_perfiles           NUMBER(2) NOT NULL,
    activo                 CHAR(1 CHAR) DEFAULT 'S' NOT NULL,

    CONSTRAINT pk_plan_suscripcion PRIMARY KEY (id_plan),
    CONSTRAINT uq_plan_nombre UNIQUE (nombre),
    CONSTRAINT ck_plan_precio CHECK (precio_mensual > 0),
    CONSTRAINT ck_plan_pantallas CHECK (pantallas_simultaneas > 0),
    CONSTRAINT ck_plan_perfiles CHECK (max_perfiles > 0),
    CONSTRAINT ck_plan_calidad CHECK (calidad_video IN ('SD','HD','4K')),
    CONSTRAINT ck_plan_activo CHECK (activo IN ('S','N'))
);

CREATE TABLE usuario (
    id_usuario                 NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_plan                    NUMBER NOT NULL,
    id_usuario_referidor       NUMBER,
    nombre                     VARCHAR2(80 CHAR) NOT NULL,
    apellido                   VARCHAR2(80 CHAR) NOT NULL,
    email                      VARCHAR2(150 CHAR) NOT NULL,
    telefono                   VARCHAR2(20 CHAR),
    fecha_nacimiento           DATE NOT NULL,
    ciudad_residencia          VARCHAR2(80 CHAR) NOT NULL,
    fecha_registro             DATE DEFAULT SYSDATE NOT NULL,
    fecha_vencimiento_pago     DATE,
    estado_cuenta              VARCHAR2(15 CHAR) DEFAULT 'ACTIVA' NOT NULL,
    referido_activo            CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    descuento_proximo_pago     NUMBER(5,2) DEFAULT 0 NOT NULL,

    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_estado CHECK (
        estado_cuenta IN ('ACTIVA','SUSPENDIDA','DESACTIVADA')
    ),
    CONSTRAINT ck_usuario_referido_activo CHECK (referido_activo IN ('S','N')),
    CONSTRAINT ck_usuario_descuento CHECK (
        descuento_proximo_pago >= 0 AND descuento_proximo_pago <= 100
    ),
    CONSTRAINT ck_usuario_referidor_self CHECK (
        id_usuario_referidor IS NULL OR id_usuario_referidor <> id_usuario
    ),
    CONSTRAINT fk_usuario_plan
        FOREIGN KEY (id_plan)
        REFERENCES plan_suscripcion(id_plan),
    CONSTRAINT fk_usuario_referidor
        FOREIGN KEY (id_usuario_referidor)
        REFERENCES usuario(id_usuario)
);

CREATE TABLE rol (
    id_rol                 NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre                 VARCHAR2(30 CHAR) NOT NULL,
    descripcion            VARCHAR2(200 CHAR),

    CONSTRAINT pk_rol PRIMARY KEY (id_rol),
    CONSTRAINT uq_rol_nombre UNIQUE (nombre)
);

CREATE TABLE usuario_rol (
    id_usuario             NUMBER NOT NULL,
    id_rol                 NUMBER NOT NULL,
    fecha_asignacion       DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_usuario_rol PRIMARY KEY (id_usuario, id_rol),
    CONSTRAINT fk_usuario_rol_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE CASCADE,
    CONSTRAINT fk_usuario_rol_rol
        FOREIGN KEY (id_rol)
        REFERENCES rol(id_rol)
);

CREATE TABLE perfil (
    id_perfil              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario             NUMBER NOT NULL,
    nombre                 VARCHAR2(60 CHAR) NOT NULL,
    avatar_url             VARCHAR2(300 CHAR),
    tipo_perfil            VARCHAR2(10 CHAR) NOT NULL,
    fecha_creacion         DATE DEFAULT SYSDATE NOT NULL,
    activo                 CHAR(1 CHAR) DEFAULT 'S' NOT NULL,

    CONSTRAINT pk_perfil PRIMARY KEY (id_perfil),
    CONSTRAINT uq_perfil_usuario_nombre UNIQUE (id_usuario, nombre),
    CONSTRAINT ck_perfil_tipo CHECK (tipo_perfil IN ('ADULTO','INFANTIL')),
    CONSTRAINT ck_perfil_activo CHECK (activo IN ('S','N')),
    CONSTRAINT fk_perfil_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE CASCADE
);

------------------------------------------------------------
-- 3. CATALOGO DE CONTENIDOS
------------------------------------------------------------

CREATE TABLE genero (
    id_genero              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre                 VARCHAR2(50 CHAR) NOT NULL,
    descripcion            VARCHAR2(200 CHAR),
    activo                 CHAR(1 CHAR) DEFAULT 'S' NOT NULL,

    CONSTRAINT pk_genero PRIMARY KEY (id_genero),
    CONSTRAINT uq_genero_nombre UNIQUE (nombre),
    CONSTRAINT ck_genero_activo CHECK (activo IN ('S','N'))
);

CREATE TABLE contenido (
    id_contenido           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_empleado_publica    NUMBER NOT NULL,
    tipo_contenido         VARCHAR2(15 CHAR) NOT NULL,
    titulo                 VARCHAR2(200 CHAR) NOT NULL,
    anio_lanzamiento       NUMBER(4) NOT NULL,
    duracion_minutos       NUMBER(6),
    sinopsis               VARCHAR2(2000 CHAR),
    clasificacion_edad     VARCHAR2(5 CHAR) NOT NULL,
    fecha_agregado         DATE DEFAULT SYSDATE NOT NULL,
    es_original            CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    activo                 CHAR(1 CHAR) DEFAULT 'S' NOT NULL,

    CONSTRAINT pk_contenido PRIMARY KEY (id_contenido),
    CONSTRAINT ck_contenido_tipo CHECK (
        tipo_contenido IN ('PELICULA','SERIE','DOCUMENTAL','MUSICA','PODCAST')
    ),
    CONSTRAINT ck_contenido_anio CHECK (
        anio_lanzamiento BETWEEN 1900 AND 2100
    ),
    CONSTRAINT ck_contenido_duracion CHECK (
        duracion_minutos IS NULL OR duracion_minutos > 0
    ),
    CONSTRAINT ck_contenido_clasificacion CHECK (
        clasificacion_edad IN ('TP','+7','+13','+16','+18')
    ),
    CONSTRAINT ck_contenido_original CHECK (es_original IN ('S','N')),
    CONSTRAINT ck_contenido_activo CHECK (activo IN ('S','N')),
    CONSTRAINT fk_contenido_empleado_publica
        FOREIGN KEY (id_empleado_publica)
        REFERENCES empleado(id_empleado)
);

CREATE TABLE contenido_genero (
    id_contenido           NUMBER NOT NULL,
    id_genero              NUMBER NOT NULL,

    CONSTRAINT pk_contenido_genero PRIMARY KEY (id_contenido, id_genero),
    CONSTRAINT fk_contenido_genero_contenido
        FOREIGN KEY (id_contenido)
        REFERENCES contenido(id_contenido)
        ON DELETE CASCADE,
    CONSTRAINT fk_contenido_genero_genero
        FOREIGN KEY (id_genero)
        REFERENCES genero(id_genero)
);

CREATE TABLE contenido_relacionado (
    id_contenido_origen    NUMBER NOT NULL,
    id_contenido_destino   NUMBER NOT NULL,
    tipo_relacion          VARCHAR2(25 CHAR) NOT NULL,
    descripcion            VARCHAR2(200 CHAR),

    CONSTRAINT pk_contenido_relacionado
        PRIMARY KEY (id_contenido_origen, id_contenido_destino, tipo_relacion),
    CONSTRAINT ck_contenido_rel_self CHECK (
        id_contenido_origen <> id_contenido_destino
    ),
    CONSTRAINT ck_contenido_rel_tipo CHECK (
        tipo_relacion IN ('SECUELA','PRECUELA','REMAKE','SPIN_OFF','VERSION_EXTENDIDA','RELACIONADO')
    ),
    CONSTRAINT fk_cont_rel_origen
        FOREIGN KEY (id_contenido_origen)
        REFERENCES contenido(id_contenido)
        ON DELETE CASCADE,
    CONSTRAINT fk_cont_rel_destino
        FOREIGN KEY (id_contenido_destino)
        REFERENCES contenido(id_contenido)
        ON DELETE CASCADE
);

CREATE TABLE temporada (
    id_temporada           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_contenido           NUMBER NOT NULL,
    numero_temporada       NUMBER(4) NOT NULL,
    titulo                 VARCHAR2(200 CHAR),
    fecha_estreno          DATE,
    descripcion            VARCHAR2(500 CHAR),

    CONSTRAINT pk_temporada PRIMARY KEY (id_temporada),
    CONSTRAINT uq_temporada_contenido_num UNIQUE (id_contenido, numero_temporada),
    CONSTRAINT ck_temporada_numero CHECK (numero_temporada > 0),
    CONSTRAINT fk_temporada_contenido
        FOREIGN KEY (id_contenido)
        REFERENCES contenido(id_contenido)
        ON DELETE CASCADE
);

CREATE TABLE episodio (
    id_episodio            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_temporada           NUMBER NOT NULL,
    numero_episodio        NUMBER(4) NOT NULL,
    titulo                 VARCHAR2(200 CHAR) NOT NULL,
    duracion_minutos       NUMBER(6) NOT NULL,
    sinopsis               VARCHAR2(2000 CHAR),
    fecha_publicacion      DATE,

    CONSTRAINT pk_episodio PRIMARY KEY (id_episodio),
    CONSTRAINT uq_episodio_temporada_num UNIQUE (id_temporada, numero_episodio),
    CONSTRAINT ck_episodio_numero CHECK (numero_episodio > 0),
    CONSTRAINT ck_episodio_duracion CHECK (duracion_minutos > 0),
    CONSTRAINT fk_episodio_temporada
        FOREIGN KEY (id_temporada)
        REFERENCES temporada(id_temporada)
        ON DELETE CASCADE
);

