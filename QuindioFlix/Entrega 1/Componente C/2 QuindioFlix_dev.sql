-- 5. PAGOS Y FACTURACION
------------------------------------------------------------

CREATE TABLE pago_suscripcion (
    id_pago                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario             NUMBER NOT NULL,
    fecha_pago             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    periodo_inicio         DATE NOT NULL,
    periodo_fin            DATE NOT NULL,
    monto_base             NUMBER(10,2) NOT NULL,
    porcentaje_descuento   NUMBER(5,2) DEFAULT 0 NOT NULL,
    monto_pagado           NUMBER(10,2) NOT NULL,
    metodo_pago            VARCHAR2(20 CHAR) NOT NULL,
    estado_pago            VARCHAR2(15 CHAR) NOT NULL,
    referencia_transaccion VARCHAR2(100 CHAR),

    CONSTRAINT pk_pago_suscripcion PRIMARY KEY (id_pago),
    CONSTRAINT ck_pago_periodo CHECK (periodo_fin >= periodo_inicio),
    CONSTRAINT ck_pago_montos CHECK (
        monto_base >= 0 AND monto_pagado >= 0
    ),
    CONSTRAINT ck_pago_descuento CHECK (
        porcentaje_descuento >= 0 AND porcentaje_descuento <= 100
    ),
    CONSTRAINT ck_pago_metodo CHECK (
        metodo_pago IN ('TARJETA_CREDITO','TARJETA_DEBITO','PSE','NEQUI','DAVIPLATA')
    ),
    CONSTRAINT ck_pago_estado CHECK (
        estado_pago IN ('EXITOSO','FALLIDO','PENDIENTE','REEMBOLSADO')
    ),
    CONSTRAINT fk_pago_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
);

