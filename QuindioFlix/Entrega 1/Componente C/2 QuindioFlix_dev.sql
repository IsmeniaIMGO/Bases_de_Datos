CREATE TABLE reproduccion (
    id_reproduccion        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_perfil              NUMBER NOT NULL,
    id_contenido           NUMBER NOT NULL,
    id_episodio            NUMBER,
    fecha_hora_inicio      TIMESTAMP NOT NULL,
    fecha_hora_fin         TIMESTAMP,
    dispositivo            VARCHAR2(15 CHAR) NOT NULL,
    porcentaje_avance      NUMBER(5,2) DEFAULT 0 NOT NULL,

    CONSTRAINT pk_reproduccion PRIMARY KEY (id_reproduccion),
    CONSTRAINT ck_reproduccion_fechas CHECK (
        fecha_hora_fin IS NULL OR fecha_hora_fin >= fecha_hora_inicio
    ),
    CONSTRAINT ck_reproduccion_dispositivo CHECK (
        dispositivo IN ('CELULAR','TABLET','TV','COMPUTADOR')
    ),
    CONSTRAINT ck_reproduccion_avance CHECK (
        porcentaje_avance >= 0 AND porcentaje_avance <= 100
    ),
    CONSTRAINT fk_reproduccion_perfil
        FOREIGN KEY (id_perfil)
        REFERENCES perfil(id_perfil)
        ON DELETE CASCADE,
    CONSTRAINT fk_reproduccion_contenido
        FOREIGN KEY (id_contenido)
        REFERENCES contenido(id_contenido),
    CONSTRAINT fk_reproduccion_episodio
        FOREIGN KEY (id_episodio)
        REFERENCES episodio(id_episodio)
);

CREATE TABLE favorito_perfil (
    id_perfil              NUMBER NOT NULL,
    id_contenido           NUMBER NOT NULL,
    fecha_agregado         DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_favorito_perfil PRIMARY KEY (id_perfil, id_contenido),
    CONSTRAINT fk_favorito_perfil_perfil
        FOREIGN KEY (id_perfil)
        REFERENCES perfil(id_perfil)
        ON DELETE CASCADE,
    CONSTRAINT fk_favorito_perfil_contenido
        FOREIGN KEY (id_contenido)
        REFERENCES contenido(id_contenido)
        ON DELETE CASCADE
);

CREATE TABLE calificacion_contenido (
    id_calificacion        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_perfil              NUMBER NOT NULL,
    id_contenido           NUMBER NOT NULL,
    estrellas              NUMBER(1) NOT NULL,
    resena                 VARCHAR2(1000 CHAR),
    fecha_calificacion     DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_calificacion_contenido PRIMARY KEY (id_calificacion),
    CONSTRAINT uq_calificacion_perfil_contenido UNIQUE (id_perfil, id_contenido),
    CONSTRAINT ck_calificacion_estrellas CHECK (
        estrellas BETWEEN 1 AND 5
    ),
    CONSTRAINT fk_calificacion_perfil
        FOREIGN KEY (id_perfil)
        REFERENCES perfil(id_perfil)
        ON DELETE CASCADE,
    CONSTRAINT fk_calificacion_contenido
        FOREIGN KEY (id_contenido)
        REFERENCES contenido(id_contenido)
        ON DELETE CASCADE
);

CREATE TABLE reporte_contenido (
    id_reporte             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario_reporta     NUMBER NOT NULL,
    id_contenido           NUMBER NOT NULL,
    id_moderador_usuario   NUMBER,
    motivo                 VARCHAR2(200 CHAR) NOT NULL,
    descripcion            VARCHAR2(1000 CHAR),
    fecha_reporte          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    estado_reporte         VARCHAR2(15 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
    fecha_resolucion       TIMESTAMP,
    observacion_resolucion VARCHAR2(1000 CHAR),

    CONSTRAINT pk_reporte_contenido PRIMARY KEY (id_reporte),
    CONSTRAINT ck_reporte_estado CHECK (
        estado_reporte IN ('PENDIENTE','EN_REVISION','RESUELTO','RECHAZADO')
    ),
    CONSTRAINT ck_reporte_fechas CHECK (
        fecha_resolucion IS NULL OR fecha_resolucion >= fecha_reporte
    ),
    CONSTRAINT fk_reporte_usuario_reporta
        FOREIGN KEY (id_usuario_reporta)
        REFERENCES usuario(id_usuario),
    CONSTRAINT fk_reporte_contenido
        FOREIGN KEY (id_contenido)
        REFERENCES contenido(id_contenido),
    CONSTRAINT fk_reporte_moderador_usuario
        FOREIGN KEY (id_moderador_usuario)
        REFERENCES usuario(id_usuario)
);

